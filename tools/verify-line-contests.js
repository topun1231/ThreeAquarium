async function verifyLineContests(page) {
  const c=id=>page.locator('#crystal-'+id);
  const journal=c('line-journal'), shows=c('line-shows'), panel=c('panel');
  const toggle=journal.locator('[data-shows-toggle]'), pick=shows.locator('[data-show-card]');
  const go=shows.locator('[data-show-visit]'), back=c('contest-line-back'), race=c('contest-card');
  const candidate=c('contest-entrant'), enter=c('contest-enter');
  const state=()=>page.evaluate(()=>aquarium.game.data.Breeding);
  const act=action=>page.evaluate(action=>aquarium.game.crystalAction(action),action);
  const check=(ok,message)=>{if(!ok)throw Error(message);};
  const member=id=>journal.locator('[data-line-member="'+id+'"]');
  const results=()=>shows.locator('[data-show-member]').evaluateAll(rows=>rows.map(row=>[row.dataset.showMember,row.textContent]));
  const accounts=async()=>{
    const s=await state();
    return JSON.stringify([s.cash,s.contests,s.individuals.map(r=>[r.id,r.contestDebuts]),s.batches.map(b=>b.rookieEntry)]);
  };
  async function openJournal(){
    await c('tab-album').click();
    if(!await journal.evaluate(el=>el.open))await journal.locator(':scope > summary').click();
  }
  await page.locator('#welcome-dismiss').click();
  await c('open').click();await c('start').click();await panel.waitFor({state:'hidden'});
  await page.clock.setFixedTime(new Date((await state()).now+100));
  await c('open').click();await c('tab-breed').click();
  await c('mother').selectOption('I4');await c('father').selectOption('I2');
  await c('breeding-tank').selectOption('breeding');await c('brood-size').selectOption('4');
  await c('plan').click();await page.waitForFunction(()=>aquarium.game.data.Breeding.batches.length===1&&!aquarium.game.busy);
  const batch=(await state()).batches[0];
  await page.clock.setFixedTime(new Date(batch.adultAt+1500));await act({type:'advance'});
  const kids=(await state()).batches[0].children.map(k=>k.id), kid=kids[1], sibling=kids[2];
  await c('tab-contest').click();await race.selectOption('colour-entry');
  await candidate.selectOption('I4');await enter.click();await c('contest-result').waitFor();
  await act({type:'rename',id:kid,name:'雪团'});
  await act({type:'nameLineBook',founderId:'I4',title:'尾白',previousTitle:null});
  await act({type:'markLineMember',founderId:'I4',id:kid,marked:true});
  await openJournal();await member(kid).click();
  check(await shows.isHidden(),'New journal opened with scores exposed');
  const before=await accounts(), cash=(await state()).cash;
  await toggle.click();
  check(await pick.inputValue()==='colour-entry' && (await results()).map(r=>r[0]).join()==='I4','Only the mother should have a recorded entry');
  check((await go.innerText()).includes('这场报名'),'The unjudged child should be able to choose the same card');
  await go.click();
  check(await candidate.inputValue()===kid && await race.inputValue()==='colour-entry' && !await c('contest-forecast').isChecked(),'Registration lost the chosen child or exposed a prediction');
  await back.click();
  check(await go.evaluate(el=>el===document.activeElement) && await member(kid).getAttribute('aria-pressed')==='true' && await accounts()===before,'Backing out changed the recorded entries or lost the origin');
  await go.click();
  await page.evaluate(()=>{const original=Storage.prototype.setItem;Storage.prototype.setItem=function(key,value){
    if(key==='aquarium.three.creatures.v1'){Storage.prototype.setItem=original;throw Error('模拟手记报名保存失败');}
    return original.call(this,key,value);
  };});
  await enter.click();await c('feedback').filter({hasText:'模拟手记报名保存失败'}).waitFor();
  check(await accounts()===before && await candidate.inputValue()===kid,'Failed registration mutated records or lost the child');
  await enter.click();await c('contest-result').waitFor();await back.click();
  const earned=await results();
  check(earned.map(r=>r[0]).join()===['I4',kid].join() && earned.every(r=>r[1].includes('雪团') && r[1].includes('分')) && earned[0][1]!==earned[1][1],'Missing the two distinguishable actual results');
  check((await state()).cash===cash,'Registered two first-theme awards');
  await page.setViewportSize({width:390,height:844});
  await shows.scrollIntoViewIfNeeded();
  check(await shows.evaluate(el=>el.scrollWidth<=el.clientWidth+1 && el.getBoundingClientRect().right<=innerWidth),'Mobile journal results overflow');
  await shows.screenshot({path:'output/playwright/line-show-results.png',animations:'disabled'});
  await shows.locator('[data-show-member="I4"]').click();await go.click();
  check(await candidate.inputValue()==='I4' && await enter.isHidden() && await c('contest-result').isVisible(),'Opening a recorded result allowed another registration');
  await back.click();
  await act({type:'rookieContest',batchId:batch.id,id:kid});
  await act({type:'exhibition',round:1,contestId:'exhibition:1',id:kid});
  await pick.selectOption('rookie:'+batch.id);
  check((await results()).map(r=>r[0]).join()===kid && (await go.innerText()).includes('挑赛场'),'The mother was invited to a closed brood race');
  await shows.locator('[data-show-member="'+kid+'"]').click();await go.click();
  check(await race.inputValue()==='rookie:'+batch.id && await candidate.inputValue()===kid && await enter.isHidden(),'Read-only brood result lost its entrant');
  await back.click();await pick.selectOption('exhibition:1');await go.click();
  check(await race.inputValue()==='exhibition:1' && await candidate.inputValue()===kid && await enter.isHidden(),'History opened another edition or group');
  await back.click();await pick.selectOption('colour-entry');await member('I4').click();
  await act({type:'rest',id:'I4'});
  check((await results()).some(r=>r[0]==='I4') && await go.isHidden(),'A resting regular entrant lost its result or could register');
  await act({type:'recall',id:'I4',tankId:'main'});await act({type:'protect',id:'I4',value:false});await act({type:'sell',id:'I4'});
  await journal.locator('[data-visit]').click();await c('family-back').click();
  check(await shows.isVisible() && await member('I4').getAttribute('aria-pressed')==='true' && await pick.inputValue()==='colour-entry','Sold mother lost her place on return from the archive');
  await member(kid).click();await go.click();
  const compare=c('contest-compare');
  await compare.locator(':scope > summary').click();await c('contest-other').selectOption('I4');
  await c('contest-other-visit').click();await c('family-back').click();
  check(await candidate.inputValue()===kid && await back.isVisible(),'Visiting the archived opponent lost the way back to the journal');
  await back.click();
  await journal.locator('[data-all]').click();await member(sibling).click();
  check(await go.isHidden(),'Unmarked sibling offered registration from a handpicked notebook');
  await act({type:'nameLineBook',founderId:'I2',title:'另一支',previousTitle:null});
  const books=journal.locator('[data-books] select');
  await books.selectOption('I2');check(await shows.isHidden(),'Switched books with the first family results still open');
  await toggle.click();check(await shows.locator('[data-no-shows]').isVisible() && !(await results()).length,'The unrelated book inherited family results');
  await page.reload();await page.waitForFunction(()=>window.aquarium?.ready);
  await c('open').click();await openJournal();await books.selectOption('I4');await member(kid).click();await toggle.click();
  check(JSON.stringify(await results())===JSON.stringify(earned),'Reload duplicated, lost, or reassigned regular results');
  const allSlots=await pick.locator('option').evaluateAll(options=>options.map(option=>option.value));
  check(allSlots.join()===['colour-entry','rookie:'+batch.id,'exhibition:1'].join(),'Saved entries mixed cards');
  await journal.locator('[data-mark]').click();
  check((await results()).map(r=>r[0]).join()==='I4' && (await state()).individuals.find(r=>r.id===kid).contestDebuts['colour-entry']!=null,'Removing a journal member erased their contest record');
  await c('tab-contest').click();check(await back.isHidden(),'Unrelated contest retained a stale return action');
  return {mother:'I4',kid,sibling,earned,allSlots,cashAfterFirstTheme:cash,returnedToFocus:true,saveRetried:true,archived:true,reloaded:true,mobileWidth:390};
}
